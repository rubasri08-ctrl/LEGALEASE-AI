# EXPORT PDF
# =========================================================

@router.post("/export/pdf")
def export_pdf(request: ExportRequest):

    try:

        # -----------------------------------------------------
        # FIND UNICODE FONT
        # -----------------------------------------------------

        font_candidates = [

            Path("C:/Windows/Fonts/arial.ttf"),

            Path("C:/Windows/Fonts/segoeui.ttf"),

            Path("C:/Windows/Fonts/calibri.ttf")

        ]

        font_path = None

        for candidate in font_candidates:

            if candidate.exists():

                font_path = candidate

                break

        if font_path is None:

            raise FileNotFoundError(
                "No Unicode TrueType font was found on this computer."
            )

        # -----------------------------------------------------
        # CREATE PDF
        # -----------------------------------------------------

        pdf = LegalEasePDF(
            font_path
        )

        pdf.add_page()

        # -----------------------------------------------------
        # DOCUMENT TITLE
        # -----------------------------------------------------

        pdf.set_font(
            "UnicodeFont",
            "",
            18
        )

        pdf.cell(
            0,
            12,
            "LEGAL DOCUMENT",
            ln=True,
            align="C"
        )

        pdf.ln(6)

        # -----------------------------------------------------
        # DOCUMENT CONTENT
        # -----------------------------------------------------

        for line in request.content.split("\n"):

            line = line.strip()

            if not line:
                continue

            # -------------------------------------------------
            # HEADING DETECTION
            # -------------------------------------------------

            is_heading = (
                line.isupper()
                or line.endswith(":")
                or any(
                    line.startswith(f"{number}.")
                    for number in range(1, 10)
                )
            )

            # -------------------------------------------------
            # BULLET DETECTION
            # -------------------------------------------------

            is_bullet = (
                line.startswith("- ")
                or line.startswith("* ")
                or line.startswith("• ")
                or line.startswith("(a)")
                or line.startswith("(b)")
                or line.startswith("(c)")
            )

            # -------------------------------------------------
            # HEADINGS
            # -------------------------------------------------

            if is_heading:

                pdf.set_font(
                    "UnicodeFont",
                    "",
                    12
                )

                pdf.multi_cell(
                    0,
                    7,
                    line
                )

                pdf.ln(2)

            # -------------------------------------------------
            # BULLET POINTS
            # -------------------------------------------------

            elif is_bullet:

                pdf.set_font(
                    "UnicodeFont",
                    "",
                    11
                )

                # Convert common bullet formats
                if line.startswith("- "):

                    line = "• " + line[2:]

                elif line.startswith("* "):

                    line = "• " + line[2:]

                pdf.multi_cell(
                    0,
                    7,
                    line
                )

                pdf.ln(1)

            # -------------------------------------------------
            # NORMAL PARAGRAPH
            # -------------------------------------------------

            else:

                pdf.set_font(
                    "UnicodeFont",
                    "",
                    11
                )

                pdf.multi_cell(
                    0,
                    7,
                    line
                )

                pdf.ln(2)

        # -----------------------------------------------------
        # GENERATE PDF BYTES
        # -----------------------------------------------------

        pdf_output = pdf.output(
            dest="S"
        )

        if isinstance(pdf_output, str):

            pdf_output = pdf_output.encode(
                "latin-1"
            )

        file_stream = BytesIO(
            pdf_output
        )

        file_stream.seek(0)

        # -----------------------------------------------------
        # RETURN PDF
        # -----------------------------------------------------

        return StreamingResponse(

            file_stream,

            media_type="application/pdf",

            headers={
                "Content-Disposition":
                    "attachment; filename=LegalEase_Document.pdf"
            }
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail=str(exc)
        )